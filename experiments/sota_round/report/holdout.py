"""Prospective second SWE-Explore split, expressed as a standalone report page."""


def add_holdout(w):
    w.page("SWE-Explore · независимые задачи",
           "Сочетание трёх способов поиска на новых задачах",
           "При одинаковом числе предъявленных строк новый метод получил F1 7,52%, авторский TF-IDF — 7,41%, "
           "а поиск по идентификаторам и путям из первого эксперимента — 8,69%.")
    w.p("Из 451 задачи с меткой Verified мы исключили все 23 задачи первого эксперимента и пример из статьи. "
        "Из оставшихся выбрали по хешу три задачи в каждом из десяти репозиториев. Все 30 задач новые, "
        "но каждый репозиторий уже встречался в пилоте. Списки пяти фрагментов для всех методов "
        "сохранили и зафиксировали контрольными суммами до обращения к эталонным строкам.")
    w.h("Что изменилось после первого эксперимента")
    w.p("К двум прежним порядкам добавили третий. Он ищет близкие написания имён из описания ошибки по "
        "группам из трёх и четырёх символов в именах и путях исходного кода. В итоговой сумме обратных "
        "рангов вес поиска по словам равен 3, прежнего поиска по идентификаторам и путям — 1, "
        "посимвольного поиска — 2. Имена обнаружились во всех 30 запросах.")
    w.tbl(["Метод", "F1 при равном числе строк", "F1 при пяти фрагментах", "Строк в пяти фрагментах"],
          [["TF-IDF авторов", "7,41%", "7,49%", "336,1"],
           ["Идентификаторы и пути", "8,69%", "9,16%", "384,7"],
           ["С объединением трёх порядков", "7,52%", "7,75%", "371,0"]], small=True)
    w.p("В основном сравнении каждую из трёх выдач сокращали с конца до самой короткой выдачи для "
        "этой задачи. В среднем это 334,0 строки. Разница между новым методом и TF-IDF составила "
        "+0,11 п. п., 95% интервал при повторной выборке репозиториев — от −3,90 до +3,77. "
        "На 9 задачах F1 вырос, на 16 совпал и на 5 снизился. При поочерёдном исключении одного "
        "репозитория разность менялась от −0,88 до +1,35 п. п.")
    w.p("Отставание от прежнего поиска по идентификаторам составило 1,16 п. п. "
        "(интервал разности от −4,19 до +1,47). По сравнению с TF-IDF выросла точность по строкам "
        "(18,19% против 13,86%), но снизилась полнота (5,70% против 7,71%). Поиск чаще попадал в нужный "
        "файл и захватывал меньшую долю его эталонных строк.")
    w.p("Построение индексов и поиск заняли в среднем 6,28 с на задачу для нового метода и 3,36 с для TF-IDF "
        "при четырёх параллельных процессах на этой машине. Вызовов языковой модели не было. "
        "Десять знакомых репозиториев ограничивают вывод о переносе на другие проекты. Измерялась локализация "
        "кода перед редактированием. Успех исправления требует отдельного запуска решателя.")
    w.source("Закреплённая версия авторского поиска TF-IDF",
             "https://github.com/Qiushao-E/SWE-Explore-Bench/blob/5602f031f2d9562d0a805f83402b536e831a5a11/explorers/rag_tfidf.py")
