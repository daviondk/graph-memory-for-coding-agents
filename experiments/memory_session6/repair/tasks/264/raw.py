def dog_age(h_age: int) -> int:
    """
    Calculate a dog's age in dog's years.
    
    The common rule of thumb is that 1 human year is equivalent to 7 dog years.
    
    Args:
        h_age: The human age in years.
        
    Returns:
        The dog's age in dog years.
    """
    return h_age * 7
