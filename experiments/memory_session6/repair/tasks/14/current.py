def find_Volume(l, b, h):
    """
    Calculate the volume of a triangular prism.
    
    Parameters:
    l (float): Length of the prism
    b (float): Base of the triangular face
    h (float): Height of the triangular face
    
    Returns:
    float: Volume of the triangular prism
    """
    return 0.5 * b * h * l
